  /// Normalize prayer text to match psalm format:
  /// - Remove "፤" after verse numbers
  /// - Renumber all verses sequentially starting from 1
  /// - Lines without a verse number get the next sequential number
  static String _normalize(String raw) {
    final lines = raw.split('\n');
    final normalized = <String>[];
    final verseNumPattern = RegExp(r'^(\d+)\s*፤?\s+(.*)');
    int verseCounter = 1;

    for (final line in lines) {
      final trimmed = line.trim();
      if (trimmed.isEmpty) continue;

      final match = verseNumPattern.firstMatch(trimmed);
      if (match != null) {
        // Line starts with a number — renumber sequentially
        normalized.add('$verseCounter ${match.group(2)}');
        verseCounter++;
      } else {
        // Line without a verse number — assign next number
        normalized.add('$verseCounter $trimmed');
        verseCounter++;
      }
    }
    return normalized.join('\n');
  }

  /// Get the Amharic prayer text by prayer index (1-17), normalized to psalm format
  static String? getPrayer(int index) {
    final raw = _prayersAm[index];
    if (raw == null) return null;
    return _normalize(raw);
  }

  /// Get the clean title for a prayer by index
  static String? getTitle(int index, String language) {
    final titles = language == 'am' ? _titlesAm : _titlesEn;
    if (index < 1 || index > titles.length) return null;
    return titles[index - 1];
  }

  /// Check if prayer text exists for given index
  static bool hasPrayer(int index) {
    return _prayersAm.containsKey(index);
  }

