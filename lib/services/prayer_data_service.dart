  /// Get the prayer index from a prayer topic string (matches the numbered prefix)
  static int? getPrayerIndexFromTopic(String topic) {
    final match = RegExp(r'^(\d+)').firstMatch(topic.trim());
    if (match != null) {
      return int.tryParse(match.group(1)!);
    }
    return null;
  }
